/**
 * 轻量中英切换：代码里保留中文原文当 key，英文查表。
 * 查不到就回退中文，新增文案不会崩。
 * 语言设置：system（跟随系统）/ zh / en。
 */
enum class AppLang(val id: String, val label: String) {
    SYSTEM("system", "跟随系统 / System"),
    ZH("zh", "中文"),
    EN("en", "English"),
}

object L10n {
    /** 当前生效语言（zh / en），由 MainActivity 在启动和切换时写入 */
    @Volatile
    var current: String = "zh"

    fun resolve(setting: String, systemTag: String): String = when (setting) {
        "zh" -> "zh"
        "en" -> "en"
        else -> if (systemTag.lowercase().startsWith("zh")) "zh" else "en"
    }

    /** 非 Compose 环境（ViewModel / 服务）用这个 */
    fun t(text: String): String = if (current == "en") lookup(text) else text

    fun lookup(text: String): String {
        en[text]?.let { return it }
        patterns.forEach { (re, repl) ->
            if (re.containsMatchIn(text)) return re.replace(text, repl)
        }
        return text
    }

